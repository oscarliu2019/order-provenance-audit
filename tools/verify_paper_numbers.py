"""Independent re-derivation of every quantitative claim in the manuscript.

The manuscript prints no typed number: each claim expands a macro from
``paper/numbers.tex``, generated by ``tools/paper_assets.py numbers``. This script
is the adversary of that generator. It re-reads the artefacts, recomputes every
macro that ``paper/main.tex`` actually uses with an independently written
expression, and fails if any value disagrees with what the manuscript prints.

It also enforces two structural properties:
  * every ``\\Num...`` macro used in main.tex is defined in numbers.tex, and
  * every macro used in main.tex has an independent check here,
so a new claim cannot be added to the paper without a verification for it.

Exit status is 0 only if all checks pass.

    python tools/verify_paper_numbers.py            # verify
    python tools/verify_paper_numbers.py --verbose  # print every claim
"""

